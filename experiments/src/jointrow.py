"""
joint_row.py - generated by Claude

Reproduces the JointGrid-style plot (scatter in the center, KDE marginals
on top/right) but tiles N of them side-by-side in a single figure.

Why not seaborn.JointGrid directly?
------------------------------------
sns.JointGrid always creates and owns its own matplotlib Figure — there's
no clean way to hand it an existing subplot region. So instead we rebuild
the same 2x2 "joint + marginals" layout by hand with GridSpec for each
column, and stack the columns in one outer GridSpec. This gives an
identical visual result to JointGrid, just tileable.

Usage
-----
    fig, axes = joint_row(
        datasets=[
            dict(x=logit1, y=attn1, hue=labels1, title="Bag A"),
            dict(x=logit2, y=attn2, hue=labels2, title="Bag B"),
            dict(x=logit3, y=attn3, hue=labels3, title="Bag C"),
        ],
        xlabel="Instance Classifier-head Logit",
        ylabel="Instance Attention Weight (Pre-softmax Linear Projection)",
        xlim_right=80,
    )
    fig.savefig("joint_row.png", dpi=200, bbox_inches="tight")
"""
from typing import Literal
import numpy as np
import matplotlib.pyplot as plt
import matplotlib.gridspec as gridspec
import seaborn as sns


def _single_joint_block(fig, outer_spec, x, y, hue, title=None,
                         xlim_right=None, scatter_kws=None, kde_kws=None,
                         ylabel=None, maintype: Literal["scatter", "kde"] = "scatter"):
    """Build one joint+marginal block inside a given SubplotSpec."""
    scatter_kws = dict(s=10, alpha=0.25) | (scatter_kws or {})
    # common_norm=False: normalize each hue level's KDE independently (area=1
    # per class) instead of scaling by class count. Without this, a heavily
    # imbalanced minority class gets visually flattened even if its shape
    # is the interesting part. Override via kde_kws={"common_norm": True}
    # if you actually want counts to matter.
    kde_kws = dict(fill=True, common_norm=False) | (kde_kws or {})

    # 2x2 nested grid: top-left = marginal_x, bottom-left = joint,
    # bottom-right = marginal_y, top-right = empty (for symmetry/legend space)
    inner = gridspec.GridSpecFromSubplotSpec(
        2, 2, subplot_spec=outer_spec,
        width_ratios=[4, 1], height_ratios=[1, 4],
        wspace=0.05, hspace=0.05,
    )

    ax_marg_x = fig.add_subplot(inner[0, 0])
    ax_joint = fig.add_subplot(inner[1, 0])
    ax_marg_y = fig.add_subplot(inner[1, 1], sharey=ax_joint)
    # top-right corner left empty (matches jointplot's blank corner)

    # mask out -inf / invalid values, same as `attention > -np.inf`
    mask = np.isfinite(x) & np.isfinite(y)
    x, y = np.asarray(x)[mask], np.asarray(y)[mask]
    hue_m = np.asarray(hue)[mask] if hue is not None else None

    # --- center scatter ---
    if maintype == "scatter":
        sns.scatterplot(x=x, y=y, hue=hue_m, ax=ax_joint, legend=False, **scatter_kws)
    elif maintype == "kde":
        sns.kdeplot(x=x,y=y,hue=hue_m, ax=ax_joint, legend=False, **scatter_kws)
    else:
        raise ValueError()
    if xlim_right is not None:
        ax_joint.set_xlim(right=xlim_right)

    # --- top marginal (x-axis KDE) ---
    sns.kdeplot(x=x, hue=hue_m, ax=ax_marg_x, legend=False, **kde_kws)
    ax_marg_x.set_xlim(ax_joint.get_xlim())
    ax_marg_x.set_xlabel("")
    ax_marg_x.set_ylabel("")
    ax_marg_x.set_xticks([])
    ax_marg_x.set_yticks([])
    ax_marg_x.tick_params(bottom=False, left=False, top=False, right=False,
                           labelbottom=False, labelleft=False)

    # --- right marginal (y-axis KDE, rotated) ---
    sns.kdeplot(y=y, hue=hue_m, ax=ax_marg_y, legend=False, **kde_kws)
    ax_marg_y.set_ylabel("")
    ax_marg_y.set_xlabel("")
    ax_marg_y.set_xticks([])
    ax_marg_y.set_yticks([])
    ax_marg_y.tick_params(bottom=False, left=False, top=False, right=False,
                           labelbottom=False, labelleft=False)

    if ylabel:
        ax_joint.set_ylabel(ylabel, fontsize=11)

    if title:
        ax_marg_x.set_title(title, fontsize=12)

    for ax in (ax_marg_x, ax_marg_y):
        sns.despine(ax=ax, left=True, bottom=True)

    return ax_joint, ax_marg_x, ax_marg_y


def joint_row(datasets, xlabel="", ylabel="", xlim_right=None,
              figsize_per_panel=(4.2, 4.2), scatter_kws=None, kde_kws=None,
              legend_labels=None, wspace=0.25, maintype = "scatter"):
    """
    Parameters
    ----------
    datasets : list of dict
        Each dict needs keys 'x', 'y', 'hue' (optional), 'title' (optional).
    xlabel, ylabel : shared axis labels (put once, centered under/left of row)
    xlim_right : optional shared right xlim (e.g. 80), applied per panel
    figsize_per_panel : (w, h) inches per panel
    legend_labels : if provided, draws one shared legend using these hue levels
    """
    n = len(datasets)
    fig = plt.figure(figsize=(figsize_per_panel[0] * n, figsize_per_panel[1]))
    outer = gridspec.GridSpec(1, n, wspace=wspace)

    joint_axes = []
    for i, d in enumerate(datasets):
        ax_joint, ax_mx, ax_my = _single_joint_block(
            fig, outer[0, i],
            x=d["x"], y=d["y"], hue=d.get("hue"),
            title=d.get("title"),
            xlim_right=xlim_right,
            scatter_kws=scatter_kws, kde_kws=kde_kws,
            # per-panel ylabel wins; falls back to the shared `ylabel` on
            # the leftmost panel only if no per-panel label is given anywhere
            ylabel=d.get("ylabel"),
            maintype=maintype
        )
        joint_axes.append(ax_joint)

    # shared x label centered under the row
    fig.text(0.5, -0.02, xlabel, ha="center", fontsize=12)

    # if nobody set a per-panel ylabel, fall back to one shared label on
    # the leftmost panel (old behavior)
    if ylabel and not any(d.get("ylabel") for d in datasets):
        joint_axes[0].set_ylabel(ylabel, fontsize=12)

    # one shared legend, built from the last joint axis's scatter handles
    if legend_labels is not None:
        handles, _ = joint_axes[-1].get_legend_handles_labels()
        if handles:
            fig.legend(handles, legend_labels, loc="upper center",
                       bbox_to_anchor=(0.5, 1.08), ncol=len(legend_labels),
                       frameon=False)

    return fig, joint_axes


if __name__ == "__main__":
    # --- demo with synthetic, heavily IMBALANCED classes (90/10 split) ---
    rng = np.random.default_rng(0)
    datasets = []
    for i, name in enumerate(["Bag A", "Bag B", "Bag C"]):
        n = 500
        labels = rng.choice(["negative", "positive"], size=n, p=[0.9, 0.1])
        logit = rng.normal(loc=np.where(labels == "positive", 5 + i, -2), scale=3)
        attention = rng.normal(loc=np.where(labels == "positive", 1.5, -1), scale=1)
        ylabel = "Instance Attention Weight" if i == 0 else f"Attention ({name})"
        datasets.append(dict(x=logit, y=attention, hue=labels, title=name, ylabel=ylabel))

    # default: common_norm=False -> each class's KDE independently normalized
    fig, axes = joint_row(
        datasets,
        xlabel="Instance Classifier-head Logit",
        xlim_right=80,
        legend_labels=["negative", "positive"],
    )
    fig.suptitle("common_norm=False (default) — minority class KDE not flattened",
                 y=1.12, fontsize=13)
    fig.savefig("/mnt/user-data/outputs/joint_row_demo.png", dpi=200, bbox_inches="tight")

    # comparison: common_norm=True -> minority class curve gets visually squashed
    fig2, axes2 = joint_row(
        datasets,
        xlabel="Instance Classifier-head Logit",
        xlim_right=80,
        legend_labels=["negative", "positive"],
        kde_kws={"common_norm": True},
    )
    fig2.suptitle("common_norm=True — minority class KDE flattened by count",
                  y=1.12, fontsize=13)
    fig2.savefig("/mnt/user-data/outputs/joint_row_demo_common_norm_true.png",
                 dpi=200, bbox_inches="tight")
    print("Saved demo figures.")
